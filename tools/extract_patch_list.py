#!/usr/bin/env python3
"""Generate src/plugin/FactoryPresets.cpp from the UD-Stomp patch list PDF.

Usage:  python3 tools/extract_patch_list.py path/to/udstomp_en2.pdf > src/plugin/FactoryPresets.cpp

Needs `pdftotext` (poppler). The PDF itself is not part of this repository;
only the parameter values read from its tables are.
"""
import html
import re
import subprocess
import sys

# Column centres (PDF points) of the per-band table, left to right.
COLS = [('band', 218), ('sw', 234), ('conn', 250), ('phase', 268), ('group', 284), ('sync', 302),
        ('wave', 318), ('time', 348), ('lcf', 364), ('hcf', 380), ('fb', 402), ('tap', 418),
        ('speed', 436), ('depth', 452), ('pan', 466), ('level', 486), ('ef', 502), ('dir', 520), ('dpan', 538)]
SKIP = {'931', '932', '933'}  # loop sampling patches: the looper is not part of this plugin
WAVES = {'SIN': 'Sine', 'TRI': 'Triangle', 'S.UP': 'SawUp', 'S.DN': 'SawDown'}


def words_by_page(pdf):
    out = subprocess.run(['pdftotext', '-bbox', pdf, '-'], capture_output=True, text=True, check=True).stdout
    for page in out.split('<page ')[1:]:
        yield [(float(a), float(b), float(c), float(d), html.unescape(w)) for a, b, c, d, w in
               re.findall(r'xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">([^<]*)<', page)]


def parse(pdf):
    patches = []
    for ws in words_by_page(pdf):
        labels = sorted([w for w in ws if w[0] < 35 and re.fullmatch(r'\d{3}', w[4])], key=lambda w: w[1])
        for lab in labels:
            y0 = lab[1]
            lines = {}
            for w in ws:
                if 45 < w[0] < 205 and y0 - 3 < w[1] < y0 + 40:
                    lines.setdefault(round(w[1] / 4), []).append(w)
            text = [' '.join(x[4] for x in sorted(v)) for _, v in sorted(lines.items())]
            rows = {}
            for w in ws:
                if w[0] > 205 and y0 - 3 < w[1] < y0 + 57:
                    col = min(COLS, key=lambda c: abs(c[1] - (w[0] + w[2]) / 2))[0]
                    rows.setdefault(round((w[1] - y0) / 7.0), {})[col] = w[4]
            patches.append((lab[4], text, [rows[k] for k in sorted(rows)]))
    return patches


def patch_name(num, lines):
    name = lines[0]
    for extra in lines[1:]:
        if extra.startswith('by ') or extra.startswith('(AC'):
            continue
        name = name[:-1] + extra if name.endswith('-') else name + ' ' + extra
    return f'{num} {name}'


def num(v, default):
    return default if v in ('-', 'OFF', None) else float(v)


def pan(v):
    if v in ('-', 'C', None):
        return 0.0
    return (-1 if v[0] == 'L' else 1) * float(v[1:])


def band_cpp(row, prev):
    if row.get('sw') != 'ON':
        return 'off()'
    r = {k: (prev.get(k) if v == '↑' else v) for k, v in row.items()}
    start, end = (int(x) for x in r['group'].split('->'))
    band = int(r['band'])
    group_end = end if (start == band and end > band) else 0
    src = 0 if r['conn'] == 'IN' else int(r['conn'])
    sync = 0 if r['sync'] == 'OFF' else int(r['sync'])
    if sync == band:
        sync = 0
    vals = [src, group_end, sync, 'Wave::' + WAVES[r['wave']], 'true' if r['phase'] == 'REV' else 'false',
            num(r['time'], 300), num(r['lcf'], 0), num(r['hcf'], 0), num(r['fb'], 0), num(r['tap'], 100),
            num(r['speed'], 0), num(r['depth'], 0), pan(r['pan']), num(r['level'], 10)]
    return 'on (' + ', '.join(f'{v:g}' if isinstance(v, float) else str(v) for v in vals) + ')'


def main():
    patches = parse(sys.argv[1])
    print('// Generated by tools/extract_patch_list.py from the UD-Stomp patch list. Do not edit by hand.')
    print('// Values are the factory patch settings (bands, routing, levels) as printed in that list.\n')
    print('#include "FactoryPresets.h"\n')
    print('namespace octaline\n{\n')
    print('namespace\n{')
    print('BandParams off() { return BandParams {}; }\n')
    print('BandParams on (int src, int groupEnd, int sync, Wave wave, bool invert, float time, float lcf, float hcf,')
    print('               float fb, float tap, float speed, float depth, float pan, float level)')
    print('{')
    print('    BandParams b;')
    print('    b.on = true; b.source = src; b.groupEnd = groupEnd; b.sync = sync; b.wave = wave; b.invert = invert;')
    print('    b.timeMs = time; b.lowCut = lcf; b.highCut = hcf; b.feedback = fb; b.tapPercent = tap;')
    print('    b.speed = speed; b.depth = depth; b.pan = pan; b.level = level;')
    print('    return b;')
    print('}\n')
    print('FactoryPreset make (const char* name, float effect, float direct, float directPan, std::array<BandParams, kNumBands> bands)')
    print('{')
    print('    FactoryPreset p { name, {} };')
    print('    p.params.band = bands;')
    print('    p.params.global.effectLevel = effect;')
    print('    p.params.global.directLevel = direct;')
    print('    p.params.global.directPan = directPan;')
    print('    return p;')
    print('}')
    print('} // namespace\n')
    print('const std::vector<FactoryPreset>& factoryPresets()\n{')
    print('    static const std::vector<FactoryPreset> presets {')
    count = 0
    for number, lines, rows in patches:
        if number in SKIP:
            continue
        assert len(rows) == 8, number
        g = {}
        for r in rows:
            for k in ('ef', 'dir', 'dpan'):
                if k in r:
                    g[k] = r[k]
        name = patch_name(number, lines).replace('"', '\\"')
        print(f'        make ("{name}", {num(g["ef"], 10):g}, {num(g["dir"], 10):g}, {pan(g["dpan"]):g}, {{')
        prev = {}
        for r in rows:
            print(f'            {band_cpp(r, prev)},')
            if r.get('sw') == 'ON':
                prev = {k: (prev.get(k) if v == '↑' else v) for k, v in r.items()}
        print('        }),')
        count += 1
    print('    };')
    print('    return presets;')
    print('}\n')
    print('} // namespace octaline')
    print(f'// {count} presets', file=sys.stderr)


if __name__ == '__main__':
    main()
